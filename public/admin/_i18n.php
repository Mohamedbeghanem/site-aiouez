function admin_catalog(?string $locale = null): array
{
    $locale ??= admin_locale();
    if ($locale === 'fr') {
        return [];
    }
    $catalog = [];
    foreach (admin_translation_source() as $source => $translations) {
        $catalog[$source] = (string)($translations[$locale] ?? $source);
    }
    return $catalog;
}

function admin_t(string $source, ?string $locale = null): string
{
    $locale ??= admin_locale();
    if ($locale === 'fr') {
        return $source;
    }
    $translations = admin_translation_source()[$source] ?? null;
    return is_array($translations) ? (string)($translations[$locale] ?? $source) : $source;
}
