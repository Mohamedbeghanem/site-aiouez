const ADMIN_LOCALES = [
    'fr' => ['label' => 'Français', 'native' => 'Français', 'flag' => '🇫🇷', 'dir' => 'ltr'],
    'en' => ['label' => 'English', 'native' => 'English', 'flag' => '🇬🇧', 'dir' => 'ltr'],
    'ar' => ['label' => 'العربية', 'native' => 'العربية', 'flag' => '🇩🇿', 'dir' => 'rtl'],
];

function admin_locale(): string
{
    static $locale = null;
    if ($locale !== null) {
        return $locale;
    }

    $requested = strtolower(trim((string)($_GET['lang'] ?? '')));
    if (isset(ADMIN_LOCALES[$requested])) {
        $locale = $requested;
        setcookie('aiouez_locale', $locale, [
            'expires' => time() + 365 * 86400,
            'path' => '/admin',
            'secure' => (string)($_SERVER['HTTPS'] ?? '') !== '',
            'httponly' => false,
            'samesite' => 'Lax',
        ]);
        $_COOKIE['aiouez_locale'] = $locale;
        return $locale;
    }

    $stored = strtolower(trim((string)($_COOKIE['aiouez_locale'] ?? 'fr')));
    $locale = isset(ADMIN_LOCALES[$stored]) ? $stored : 'fr';
    return $locale;
}

function admin_direction(?string $locale = null): string
{
    $locale ??= admin_locale();
    return (string)(ADMIN_LOCALES[$locale]['dir'] ?? 'ltr');
}

function admin_language_url(string $locale): string
{
    $query = $_GET;
    $query['lang'] = isset(ADMIN_LOCALES[$locale]) ? $locale : 'fr';
    unset($query['token']);
    return '/admin/?' . http_build_query($query);
}

